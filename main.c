static SDL_Palette  *palette  = NULL;

// make sure bytes is a statically allocated 1d array
// dimensions of (w x h).
static void rotate(unsigned char *bytes, unsigned char *rotated) {
  // because each byte is 8 pixels "wide", width in bytes != width in pixels.
  // however, no such conversion is needed because a byte is 1 pixel "tall".
  const size_t w = WIDTH / BYTES_TO_BITS;
  const size_t h = HEIGHT;
  uint8_t n = 0;
  unsigned int overflow = 0;
  for (size_t i = 0; i < SIZE; i++) {
    size_t row = i / w;
    size_t col = (i % h);
    unsigned char byte = bytes[i];
    printf("byte: %d\n", i);
    printf("(%02d, %02d): %02x -> ", row, col, byte);
    printf("\n");
    // loop bit 7 (MSB) -> 0 (LSB)
    uint8_t y = col % 8;
    unsigned char rotated_byte = 0x0;
    for (uint8_t j = 0; j < BYTES_TO_BITS; j++) {
      uint8_t bit_index = j;
      unsigned char mask = (0x1 << bit_index);
      unsigned char bit = (byte & mask) >> bit_index;
      rotated_byte |= (bit << bit_index);
      // get the current 1 byte high chunk
      unsigned int x = (i/8 + (j*w));
      // start on a new row if we "fill up" the current one.
      unsigned int overflow = i/WIDTH;
      // this is the magic part
      // quite obtuse, i should try & write more clearly.
      size_t addr = x + overflow*WIDTH - (w*overflow);
      printf("  Writing bit %d @ (%02d, %02d): %x", j, addr, y, bit);
      rotated[addr] |= (bit << y);
      printf("\n");
    }
    printf("\n");
  }
}

/* This function runs once at startup. */
SDL_AppResult SDL_AppInit(void **appstate, int argc, char *argv[])
{
  /* Create the window */
  if (!SDL_CreateWindowAndRenderer("Preview", WIDTH*SCALE, HEIGHT*SCALE, SDL_WINDOW_UTILITY, &window, &renderer)) {
      SDL_Log("Couldn't create window and renderer: %s", SDL_GetError());
      return SDL_APP_FAILURE;
  }
  
  SDL_SetDefaultTextureScaleMode(renderer, SDL_SCALEMODE_PIXELART);

  unsigned char pixels[SIZE];
  memset(pixels, 0, SIZE);
  rotate(bytes, pixels);
  surface = SDL_CreateSurfaceFrom(WIDTH, HEIGHT, SDL_PIXELFORMAT_INDEX1LSB, pixels, WIDTH / BYTES_TO_BITS);
  if (!surface)
  {
    SDL_Log("Did not initialize surface: %s", SDL_GetError());
    return SDL_APP_FAILURE;
  }

  const uint8_t NUM_COLORS = 2;
  palette = SDL_CreatePalette(NUM_COLORS);
  const SDL_Color colors[] = {
    {0,0,0,255},
    {255,255,255,255}
  };
  SDL_SetPaletteColors(palette, colors, 0, NUM_COLORS);
  SDL_SetSurfacePalette(surface, palette);
  SDL_DestroyPalette(palette);

  texture = SDL_CreateTextureFromSurface(renderer, surface);
  if (!texture)
  {
    SDL_Log("Couldn't create texture from surface: %s", SDL_GetError());
    return SDL_APP_FAILURE;
  }

  SDL_DestroySurface(surface);

  return SDL_APP_CONTINUE;
}

/* This function runs when a new event (mouse input, keypresses, etc) occurs. */
SDL_AppResult SDL_AppEvent(void *appstate, SDL_Event *event)
{
    if (event->type == SDL_EVENT_QUIT) {
        return SDL_APP_SUCCESS;  /* end the program, reporting success to the OS. */
    }
    return SDL_APP_CONTINUE;
}

/* This function runs once per frame, and is the heart of the program. */
SDL_AppResult SDL_AppIterate(void *appstate)
{
    SDL_RenderClear(renderer);
    SDL_RenderTexture(renderer, texture, NULL, NULL);
    SDL_RenderPresent(renderer);

    return SDL_APP_CONTINUE;
}

/* This function runs once at shutdown. */
void SDL_AppQuit(void *appstate, SDL_AppResult result)
{
  SDL_DestroyTexture(texture);
}
