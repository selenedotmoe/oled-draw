/* This function runs once at startup. */
SDL_AppResult SDL_AppInit(void **appstate, int argc, char *argv[])
{
  /* Create the window */
  if (!SDL_CreateWindowAndRenderer("Hello World", WIDTH*SCALE, HEIGHT*SCALE, SDL_WINDOW_ALWAYS_ON_TOP, &window, &renderer)) {
      SDL_Log("Couldn't create window and renderer: %s", SDL_GetError());
      return SDL_APP_FAILURE;
  }
  
  SDL_SetDefaultTextureScaleMode(renderer, SDL_SCALEMODE_PIXELART);

  char rotated[SIZE];
  memcpy(rotated, bytes, SIZE);
  //rotate_bits(bytes, rotated, WIDTH, HEIGHT);
  surface = SDL_CreateSurfaceFrom(WIDTH, HEIGHT, SDL_PIXELFORMAT_INDEX1LSB, rotated, WIDTH / BYTES_TO_BITS);
  if (!surface)
  {
    SDL_Log("Did not initialize surface: %s", SDL_GetError());
    return SDL_APP_FAILURE;
  }

  const uint8_t NUM_COLORS = 2;
  palette = SDL_CreatePalette(NUM_COLORS);
  const SDL_Color colors[] = {
    {0,0,0,255},
    {255,255,255,255}
  };
  SDL_SetPaletteColors(palette, colors, 0, NUM_COLORS);
  SDL_SetSurfacePalette(surface, palette);
  SDL_DestroyPalette(palette);

  texture = SDL_CreateTextureFromSurface(renderer, surface);
  if (!texture)
  {
    SDL_Log("Couldn't create texture from surface: %s", SDL_GetError());
    return SDL_APP_FAILURE;
  }

  if (!SDL_SavePNG(surface, "test.png")) {
    SDL_Log("Couldn't save PNG file: %s", SDL_GetError());
  }

  SDL_DestroySurface(surface);

  return SDL_APP_CONTINUE;
}

/* This function runs when a new event (mouse input, keypresses, etc) occurs. */
SDL_AppResult SDL_AppEvent(void *appstate, SDL_Event *event)
{
    if (event->type == SDL_EVENT_QUIT) {
        return SDL_APP_SUCCESS;  /* end the program, reporting success to the OS. */
    }
    return SDL_APP_CONTINUE;
}

/* This function runs once per frame, and is the heart of the program. */
SDL_AppResult SDL_AppIterate(void *appstate)
{
    SDL_RenderClear(renderer);
    //SDL_UpdateTexture(texture, NULL, bytes, WIDTH * BYTES_TO_BITS);
    SDL_RenderTexture(renderer, texture, NULL, NULL);
    SDL_RenderPresent(renderer);

    return SDL_APP_CONTINUE;
}

/* This function runs once at shutdown. */
void SDL_AppQuit(void *appstate, SDL_AppResult result)
{

  SDL_DestroyTexture(texture);
}
